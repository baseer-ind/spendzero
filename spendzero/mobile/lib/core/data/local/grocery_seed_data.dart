library;

class GroceryStore {
  const GroceryStore({
    required this.id,
    required this.name,
    required this.brandTagline,
    required this.categories,
    required this.avgRating,
    required this.reviewCount,
    required this.deliveryTimeMins,
    required this.distanceKm,
    required this.priceTier,
    required this.isTrending,
    required this.isFeatured,
    required this.bannerColorSeed,
    required this.productIds,
  });

  final String id;
  final String name;
  final String brandTagline;
  final List<String> categories;
  final double avgRating;
  final int reviewCount;
  final int deliveryTimeMins;
  final double distanceKm;
  final String priceTier;
  final bool isTrending;
  final bool isFeatured;
  final String bannerColorSeed;
  final List<String> productIds;
}

class GroceryProduct {
  const GroceryProduct({
    required this.id,
    required this.storeId,
    required this.name,
    required this.description,
    required this.category,
    required this.unit,
    required this.pricePaise,
    this.mrpPaise,
    this.isBestSeller = false,
    this.isTrending = false,
    this.isNewArrival = false,
    required this.tags,
    required this.rating,
    required this.reviewCount,
  });

  final String id;
  final String storeId;
  final String name;
  final String description;
  final String category;
  final String unit;
  final int pricePaise;
  final int? mrpPaise;
  final bool isBestSeller;
  final bool isTrending;
  final bool isNewArrival;
  final List<String> tags;
  final double rating;
  final int reviewCount;

  int? get discountPercent {
    if (mrpPaise == null || mrpPaise! <= pricePaise) return null;
    return (((mrpPaise! - pricePaise) / mrpPaise!) * 100).round();
  }
}

