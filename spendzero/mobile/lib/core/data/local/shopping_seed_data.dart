List<ShoppingProduct> productsForBrand(String brandId) =>
    allShoppingProducts.where((p) => p.brandId == brandId).toList();

List<Review> shoppingReviewsFor(String targetId) =>
    allShoppingReviews.where((r) => r.targetId == targetId).toList();

ShoppingProduct? findShoppingProductById(String id) {
  for (final p in allShoppingProducts) {
    if (p.id == id) return p;
  }
  return null;
}

ShoppingBrand? findShoppingBrandById(String id) {
  for (final b in allShoppingBrands) {
    if (b.id == id) return b;
  }
  return null;
}

List<dynamic> searchShoppingSeed(String query) {
  final q = query.trim().toLowerCase();
  if (q.isEmpty) return const [];
  final brandResults = allShoppingBrands.where(
    (b) => b.name.toLowerCase().contains(q) || b.categories.any((c) => c.toLowerCase().contains(q)),
  );
  final productResults = allShoppingProducts.where(
    (p) =>
        p.name.toLowerCase().contains(q) ||
        p.category.toLowerCase().contains(q) ||
        p.tags.any((t) => t.toLowerCase().contains(q)),
  );
  return [...brandResults, ...productResults];
}

List<ShoppingProduct> shoppingTodaysOffers() => allShoppingProducts
    .where((p) => p.mrpPaise != null && p.mrpPaise! > p.pricePaise)
    .toList();

List<ShoppingBrand> trendingShoppingBrands() =>
    allShoppingBrands.where((b) => b.isTrending).toList();

List<ShoppingProduct> trendingShoppingProducts() =>
    allShoppingProducts.where((p) => p.isTrending).toList();

List<ShoppingProduct> bestSellerShoppingProducts() =>
    allShoppingProducts.where((p) => p.isBestSeller).toList();
